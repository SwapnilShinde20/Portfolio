export const calculateSizes = (isSmall, isMobile, isTablet) => {
  return {
    deskScale: isSmall ? 0.01 : isMobile ? 0.02 : 0.025,
    deskPosition: isSmall
      ? [0.1, -1, 2]
      : isMobile
        ? [0.2, -2, 0]
        : [0, -2.5, 1],
    cubePosition: isSmall
      ? [2, -2.5, 0]
      : isMobile
        ? [3, -2.5, 0]
        : isTablet
          ? [4, -3, 0]
          : [5, -2.5, 0],
    reactLogoPosition: isSmall
      ? [2.2, 1, 0]
      : isMobile
        ? [3.5, 1, 0]
        : isTablet
          ? [4.5, -0.5, 0]
          : [5.3, 0.5, 0],
    ringPosition: isSmall
      ? [-9, 4, 0]
      : isMobile
        ? [-13, 4, 0]
        : isTablet
          ? [-24, -1, 0]
          : [-28, 5, 0],
    targetPosition: isSmall
      ? [-6, -10, -10]
      : isMobile
        ? [-8, -10, -10]
        : isTablet
          ? [-11, -7, -10]
          : [-13, -10, -10],
  };
};

